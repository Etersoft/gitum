COMMIT_URL_RE = re.compile(r'/(?:-/)?commits?/([0-9a-f]{7,40})\b')


def _pick_all(repo, wt, commits, what):
	for sha in commits:
		res = wt.run('-c', 'rerere.enabled=true', 'cherry-pick', '--allow-empty', '--empty=drop', sha, check=False)
		if res.returncode != 0:
			files = wt.unmerged_files()
			wt.run('cherry-pick', '--abort', check=False)
			raise NeedsHuman('%s: %s (%s) does not apply: %s' % (what, repo.git.commit_info(sha)['subject'],
									 sha[:12], ', '.join(files) or res.stderr.decode().strip()),
					 commit=sha, files=files)


def _set_branch(repo, branch, tip):
	ref = 'refs/heads/' + branch
	old = repo.git.rev(ref)
	if old == tip:
		return
	tr = RefTransaction(repo.git)
	tr.update(ref, tip, old or None)
	with repo.committing(tr, [(branch, old, tip)], kind='branch'):
		pass


def base_short(spec):
	return spec.split(':', 1)[-1].replace('/', '-')


# variants

def port(repo, name, to, branch=None):
	"""Put the changes of a series onto another base as a variant branch."""
	git = repo.git
	with repo.lock():
		series_mod.check_claims(repo, [name])
		journal = repo.journal()
		meta = series_mod.load(journal, name)
		if meta.get('changes') is None:
			raise GitumError('series %s has no branch recorded: gitum series checkout first' % name)
		start = git.rev(series_mod.base_ref(journal.config, to))
		if not start:
			raise GitumError('base %s does not exist' % to)
		branch = branch or 'series/%s@%s' % (name, base_short(to))
		commits = [c['sha'] for c in meta['changes']]
		# changes already in the target base are not ported again
		in_base = {line.split()[1] for line in git.lines('cherry', start, meta['tip'], meta['base_sha'])
			   if line.startswith('-')}
		wt = repo.add_worktree(start, 'port-' + name)
		try:
			_pick_all(repo, wt, [c for c in commits if c not in in_base], 'port of %s' % name)
			tip = wt.rev('HEAD')
		finally:
			repo.remove_worktree(wt.cwd)
		_set_branch(repo, branch, tip)
		journal = repo.journal()
		meta = series_mod.load(journal, name)
		meta.setdefault('variants', {})[to] = {'branch': branch, 'base_sha': start, 'tip': tip}
		writer = JournalWriter(git, journal.sha)
		writer.put_json(series_mod.meta_path(name), meta)
		writer.commit('gitum: series %s: variant on %s' % (name, to), [tip])
		return {'branch': branch, 'tip': tip, 'already_in_base': sorted(in_base), 'ported': len(commits) - len(in_base)}


def variants(repo, name):
	"""Compare the main branch of a series with its variants (patch-ids and range-diff)."""
	git = repo.git
	journal = repo.journal()
	meta = series_mod.load(journal, name)
	result = {}
	main_range = (meta['base_sha'], meta['tip'])
	main_pids = git.patch_ids(git.rev_list('%s..%s' % main_range))
	main_infos = git.commit_infos(main_pids)
	main_subjects = {main_infos[s]['subject']: pid for s, pid in main_pids.items()}
	for spec, v in (meta.get('variants') or {}).items():
		tip = git.rev('refs/heads/' + v['branch']) or v['tip']
		base = git.merge_base(git.rev(series_mod.base_ref(journal.config, spec)) or v['base_sha'], tip) or v['base_sha']
		pids = git.patch_ids(git.rev_list('%s..%s' % (base, tip)))
		infos = git.commit_infos(pids)
		subjects = {infos[s]['subject']: pid for s, pid in pids.items()}
		only_main = sorted(set(main_subjects) - set(subjects))
		only_variant = sorted(set(subjects) - set(main_subjects))
		differ = sorted(s for s in set(main_subjects) & set(subjects) if main_subjects[s] != subjects[s])
		rd = git.out('range-diff', '--no-color', '%s..%s' % main_range, '%s..%s' % (base, tip), check=False)
		result[spec] = {'branch': v['branch'], 'only_main': only_main, 'only_variant': only_variant,
				'differ': differ, 'diverged': bool(only_main or only_variant or differ), 'range_diff': rd}
	return result


# queue

ACTIVE_STATES = ('review', 'queued', 'sent', 'approved')
DEFAULT_TARGET = 'upstream'
# [queue.markdown]: sections and their order, the fields shown as columns, titles of both
MD_DEFAULT = {
	'title': 'Upstream queue',
	'generated': 'Generated by gitum; do not edit by hand.',
	'next': 'Next to send',
	'nothing': 'Nothing to send now',
	'paused': 'The queue is paused',
	'sections': ['sent', 'queued', 'review', 'draft', 'done'],
	'fields': ['position', 'name', 'state', 'updated', 'patches', 'internal_mr', 'pr', 'bugs', 'depends', 'note'],
	'done-fields': ['name', 'merged_at', 'release', 'upstream_commit', 'patches', 'pr', 'note'],
	'titles': {
		'sent': 'Sent upstream', 'queued': 'Queue', 'review': 'Internal review', 'draft': 'Waiting to be queued',
		'done': 'Done', 'position': '#', 'name': 'Series', 'state': 'State', 'updated': 'Updated',
		'patches': 'Patches', 'internal_mr': 'Internal MR', 'pr': 'Upstream MR', 'bugs': 'Bugs',
		'depends': 'Depends', 'note': 'Note', 'reviewer': 'Reviewer', 'release': 'Release',
		'upstream_commit': 'Commit', 'merged_at': 'Merged', 'target': 'Target', 'version': 'Version',
	},
}
SECTION_STATES = {'sent': ('sent', 'approved'), 'queued': ('queued',), 'review': ('review',), 'draft': ('draft',)}


def queue_path(target):
	return 'queue/%s.json' % target


def targets(journal):
	names = {m.get('target') or DEFAULT_TARGET for m in series_mod.load_all(journal).values()}
	names |= {n[:-len('.json')] for n in journal.list('queue') if n.endswith('.json')}
	return sorted(names or {DEFAULT_TARGET})


def series_row(name, meta, all_series, cfg=None):
	"""All fields of a series a queue can show."""
	return {'name': name, 'state': meta.get('state', ''), 'position': meta.get('position'),
		'depends': meta.get('depends', []),
		'blocked_by': [d for d in meta.get('depends', []) if all_series.get(d, {}).get('state') != 'merged'],
		'pr': meta.get('pr', ''), 'internal_mr': meta.get('internal_mr', ''), 'bugs': meta.get('bugs', []),
		'patches': len(meta.get('changes') or []) or len(meta.get('patch_files') or []),
		'version': meta.get('version', ''), 'updated': meta.get('updated', ''), 'note': meta.get('note', ''),
		'reviewer': meta.get('reviewer', ''), 'release': meta.get('release', ''),
		'upstream_commit': meta.get('upstream_commit', ''), 'merged_at': meta.get('merged_at', ''),
		'target': meta.get('target') or DEFAULT_TARGET,
		'bug_links': bugs_mod.of_series(cfg, meta) if cfg else []}


def queue_one(journal, all_series, target):
	"""The queue of one target: rows in order and the series that may be sent next."""
	cfg = journal.config
	one_at_a_time = cfg.queue.get('one-at-a-time', True)
	state = journal.read_json(queue_path(target), {})
	mine = {n: m for n, m in all_series.items() if (m.get('target') or DEFAULT_TARGET) == target}
	order = {'sent': 0, 'approved': 0, 'queued': 1, 'review': 2}
	by_position = lambda n: (mine[n].get('position', 10 ** 6), n)
	active = sorted((n for n, m in mine.items() if m.get('state') in ACTIVE_STATES),
			key=lambda n: (order[mine[n]['state']],) + by_position(n))
	waiting_review = [n for n in active if mine[n]['state'] == 'sent']
	rows, next_ = [], None
	for n in active:
		row = series_row(n, mine[n], all_series, cfg)
		rows.append(row)
		if next_ is None and row['state'] == 'queued' and not row['blocked_by'] and \
				not (one_at_a_time and waiting_review) and not state.get('paused'):
			next_ = n
	drafts = [series_row(n, mine[n], all_series, cfg)
		  for n in sorted((n for n, m in mine.items() if m.get('state') == 'draft'), key=by_position)]
	done = sorted((n for n, m in mine.items() if m.get('state') in series_mod.DONE_STATES),
		      key=lambda n: mine[n].get('merged_at') or mine[n].get('updated', ''),
		      reverse=True)[:cfg.queue.get('done-limit', 20)]
	done_rows = [series_row(n, mine[n], all_series, cfg) for n in done]
	reason = ''
	if next_ is None:
		if state.get('paused'):
			reason = 'paused: %s' % (state.get('reason') or 'no reason given')
		elif one_at_a_time and waiting_review:
			reason = 'waiting for %s (one at a time until approved or merged)' % ', '.join(waiting_review)
		elif not any(r['state'] == 'queued' for r in rows):
			reason = 'the queue is empty'
		else:
			reason = 'all queued series wait for their dependencies'
	return {'target': target, 'rows': rows, 'drafts': drafts, 'done': done_rows, 'next': next_, 'reason': reason,
		'paused': bool(state.get('paused')), 'pause_reason': state.get('reason', '')}


def queue(repo, target=None):
	journal = repo.journal()
	all_series = series_mod.load_all(journal)
	names = [target] if target else targets(journal)
	return {'queues': {t: queue_one(journal, all_series, t) for t in names},
		'bugs': bugs_mod.index(journal.config, all_series)}


def queue_add(repo, name, position=None):
	with repo.lock():		# the position is computed and taken in one step
		journal = repo.journal()
		if position is None:
			positions = [m.get('position', 0) for m in series_mod.load_all(journal).values() if m.get('position')]
			position = max(positions, default=0) + 1
		return series_mod.set_(repo, name, {'state': 'queued', 'position': int(position)})


def queue_pause(repo, target, paused, reason=''):
	with repo.lock():
		journal = repo.journal()
		data = {'paused': paused, 'reason': reason if paused else '', 'since': now()}
		writer = JournalWriter(repo.git, journal.sha)
		writer.put_json(queue_path(target), data)
		writer.commit('gitum: queue %s %s%s' % (
			target, 'paused' if paused else 'resumed', (': ' + reason) if reason else ''))
	return data


def md_cell(row, field, index, tz=None):
	value = row.get(field)
	if field == 'position':
		return str(index)
	if field == 'state':
		return row['state'] + ((' ' + row['version']) if row.get('version') else '')
	if field in ('updated', 'merged_at'):
		return local_date(value or row.get('updated') or '', tz)
	if field in ('pr', 'internal_mr'):
		return md_link(value)
	if field == 'upstream_commit':
		return (value or '')[:12]
	if field == 'bugs' and row.get('bug_links'):
		return ', '.join(bugs_mod.md_bug(i) for i in row['bug_links'])
	if field == 'depends':
		return ', '.join(('~~%s~~' % d) if d not in row.get('blocked_by', []) else d for d in value or [])
	if isinstance(value, list):
		return ', '.join(str(v) for v in value)
	return '' if value is None else str(value).replace('|', '\\|')


def _md_table(fields, titles, rows, tz=None):
	lines = ['| ' + ' | '.join(titles.get(f, f) for f in fields) + ' |', '|' + '---|' * len(fields)]
	for i, r in enumerate(rows, 1):
		lines.append('| ' + ' | '.join(md_cell(r, f, i, tz) for f in fields) + ' |')
	return lines


def queue_markdown(data, labels=None):
	"""Markdown of the queues, shaped by [queue.markdown] in gitum.toml (see MD_DEFAULT)."""
	labels = dict(labels or {})
	conf = {**MD_DEFAULT, **labels, 'titles': {**MD_DEFAULT['titles'], **labels.get('titles', {})}}
	titles = conf['titles']
	lines = ['# ' + conf['title'], '', conf['generated'], '']
	for target, q in data['queues'].items():
		if len(data['queues']) > 1:
			lines += ['## %s' % target, '']
		if q['paused']:
			lines.append('**%s:** %s' % (conf['paused'], q['pause_reason']))
		elif q['next']:
			lines.append('%s: **%s**' % (conf['next'], q['next']))
		else:
			lines.append('%s: %s.' % (conf['nothing'], q['reason']))
		lines.append('')
		for section in conf['sections']:
			if section == 'bugs':
				continue
			if section == 'done':
				rows, fields = q['done'], conf['done-fields']
			elif section == 'draft':
				rows, fields = q['drafts'], conf['fields']
			else:
				rows, fields = [r for r in q['rows'] if r['state'] in SECTION_STATES.get(section, ())], conf['fields']
			if rows:
				lines += ['### ' + titles.get(section, section), ''] + _md_table(fields, titles, rows, conf.get('timezone')) + ['']
	if 'bugs' in conf['sections'] and data.get('bugs'):
		level = '## ' if len(data['queues']) > 1 else '### '
		lines += [level + titles.get('bugs', 'Bugs'), ''] + \
			bugs_mod.markdown_table(data['bugs'], conf.get('bug-titles'), conf.get('timezone')) + ['']
	return '\n'.join(lines).rstrip('\n') + '\n'


# preparing for upstream

def clean_message(message, strip):
	keep = []
	for line in message.rstrip('\n').split('\n'):
		if any(line.lower().startswith(t.lower() + ':') for t in strip):
			continue
		keep.append(line)
	while keep and not keep[-1].strip():
		keep.pop()
	return '\n'.join(keep) + '\n'


def prepare(repo, name, onto=None, branch=None, push=None, directory=None, strip=None, lint=True,
	    with_depends=True, first_date=None, force=False):
	"""Build the upstream form of a series: fresh base, clean messages, new dates; optionally push it.

	Dependencies must be merged upstream already; with force their commits
	are included instead.
	"""
	with repo.lock():
		return _prepare(repo, name, onto, branch, push, directory, strip, lint, with_depends, first_date, force)


def _prepare(repo, name, onto, branch, push, directory, strip, lint, with_depends, first_date, force):
	git = repo.git
	series_mod.check_claims(repo, [name])
	journal = repo.journal()
	cfg = journal.config
	all_series = series_mod.load_all(journal)
	meta = series_mod.load(journal, name)
	if meta.get('changes') is None:
		raise GitumError('series %s has no branch recorded' % name)
	upstream_spec = ('upstream:' + meta['upstream']) if meta.get('upstream') else \
		(meta['base'] if meta['base'].startswith('upstream:') else None)
	if not onto:
		if not upstream_spec:
			names = [n for n in series_mod.order(all_series, [name])]
			specs = [all_series[n]['base'] for n in names if all_series[n]['base'].startswith('upstream:')]
			upstream_spec = specs[0] if specs else None
		if not upstream_spec:
			raise GitumError('series %s: no upstream base, use --onto' % name)
		onto = series_mod.base_ref(cfg, upstream_spec)
	start = git.rev(onto)
	if not start:
		raise GitumError('%s does not exist' % onto)
	if directory is None and upstream_spec and upstream_spec.split(':', 1)[1] in cfg.upstreams:
		directory = cfg.upstreams[upstream_spec.split(':', 1)[1]].prefix or None
	strip = strip if strip is not None else cfg.series.get('strip-trailers', DEFAULT_STRIP)
	lint_re = re.compile(cfg.series['subject-lint']) if lint and cfg.series.get('subject-lint') else None
	names = series_mod.order(all_series, [name]) if with_depends else [name]
	unmerged = [n for n in names if n != name and all_series[n].get('state') != 'merged']
	if unmerged and not force:
		raise NeedsHuman('series %s depends on %s, not merged upstream yet; send it after them (or use --force '
				 'to include their commits)' % (name, ', '.join(unmerged)), depends=unmerged)
	commits = []
	for n in names:
		m = all_series[n]
		if m.get('state') == 'merged' and n != name:
			continue
		commits += [c['sha'] for c in (m.get('changes') or [])]
	in_base = {line.split()[1] for line in git.lines('cherry', start, meta['tip'], meta['base_sha'])
		   if line.startswith('-')} if meta.get('tip') and git.merge_base(start, meta['tip']) else set()
	commits = [c for c in commits if c not in in_base]
	if not commits:
		raise GitumError('series %s: nothing left to send, everything is in %s' % (name, onto))
	problems = []
	first = datetime.datetime.fromisoformat(first_date) if first_date else datetime.datetime.now().astimezone()
	wt = repo.add_worktree(start, 'prepare-' + name)
	infos = git.commit_infos(commits)
	try:
		for sha in commits:
			info = infos[sha]
			before = wt.rev('HEAD')
			if directory:
				patch = git.run('format-patch', '--stdout', '-1', '--relative=' + directory, sha).stdout
				res = wt.run('am', '--keep-cr', '-3', input=patch, check=False)
				if res.returncode != 0:
					wt.run('am', '--abort', check=False)
					raise NeedsHuman('%s: %s does not apply under %s' % (name, info['subject'], directory))
			else:
				_pick_all(repo, wt, [sha], 'prepare %s' % name)
			if wt.rev('HEAD') == before:
				continue		# already upstream: dropped as empty
			message = clean_message(info['message'], strip)
			# one second apart, so that tools sorting by date keep the order
			date = (first + datetime.timedelta(seconds=commits.index(sha))).isoformat(timespec='seconds')
			wt.run('commit', '--amend', '--allow-empty', '--no-verify', '-q', '--date=' + date, '-F', '-',
			       input=message)
			subject = message.split('\n', 1)[0]
			if lint_re and not lint_re.match(subject):
				problems.append('subject does not match %s: %s' % (lint_re.pattern, subject))
		tip = wt.rev('HEAD')
	finally:
		repo.remove_worktree(wt.cwd)
	if problems:
		raise NeedsHuman('series %s is not ready: %s' % (name, '; '.join(problems)), problems=problems)
	branch = branch or meta.get('upstream_branch') or name
	ref_branch = 'upstream/' + branch
	_set_branch(repo, ref_branch, tip)
	result = {'series': name, 'branch': ref_branch, 'tip': tip, 'onto': start, 'commits': len(commits),
		  'skipped_in_base': sorted(in_base),
		  'range_diff': git.out('range-diff', '--no-color', '%s..%s' % (meta['base_sha'], meta['tip']),
					'%s..%s' % (start, tip), check=False) if not directory else ''}
	if push:
		git.run('push', '--quiet', '--force', push, '%s:refs/heads/%s' % (tip, branch))
		result['pushed'] = '%s/%s' % (push, branch)
	with repo.lock():
		journal = repo.journal()
		meta = series_mod.load(journal, name)
		meta['prepared'] = {'onto': start, 'tip': tip, 'branch': ref_branch, 'pushed': result.get('pushed', ''),
				    'date': now()}
		if push:
			meta['upstream_branch'] = branch
		writer = JournalWriter(git, journal.sha)
		writer.put_json(series_mod.meta_path(name), meta)
		writer.commit('gitum: prepare %s on %s' % (name, start[:12]), [tip])
	return result


# backports

def resolve_commit(git, spec):
	"""A commit from a sha or a forge commit URL."""
	m = COMMIT_URL_RE.search(spec)
	sha = git.rev(m.group(1) if m else spec)
	if not sha:
		raise GitumError('commit %s is not in the repository: fetch the upstream first' % spec)
	return sha, spec if m else ''


def backport(repo, specs, into, series_name=None, drop_on=None):
	"""Cherry-pick upstream commits onto a layer with an Origin: trailer and fate backport."""
	git = repo.git
	with repo.lock():
		journal = repo.journal()
		cfg = journal.config
		if into not in cfg.layers:
			raise GitumError('unknown layer %s' % into)
		layer = cfg.layers[into]
		tip = git.rev('refs/heads/' + layer.branch)
		st = journal.layer(into)
		layer_pids = {c.patch_id for c in st.changes} if st else set()
		layer_text = git.out('log', '--format=%B', '%s..%s' % (st.base, tip)) if st else ''
		wt = repo.add_worktree(tip, 'backport-' + into)
		picked = []
		try:
			for spec in specs:
				sha, url = resolve_commit(git, spec)
				if git.is_ancestor(sha, tip) or sha in layer_text or \
						git.patch_ids([sha]).get(sha) in layer_pids:
					raise GitumError('%s is already in %s' % (sha[:12], layer.branch))
				_pick_all(repo, wt, [sha], 'backport')
				message = git.commit_info(sha)['message'].rstrip('\n')
				message += '\n\n' if not re.search(r'\n[A-Za-z-]+: .*$', message) else '\n'
				message += 'Origin: %s\n' % (url or 'upstream commit ' + sha)
				wt.run('commit', '--amend', '--no-verify', '-q', '-F', '-', input=message)
				picked.append({'origin': sha, 'sha': wt.rev('HEAD'), 'subject': git.commit_info(sha)['subject']})
			new_tip = wt.rev('HEAD')
		finally:
			repo.remove_worktree(wt.cwd)
		def mark(tracker, st):
			by_sha = {c.sha: c.gitum_id for c in st.changes}
			for p in picked:
				meta = {'origin': p['origin']}
				if drop_on:
					meta['drop_on'] = drop_on
				if series_name:
					meta['series'] = series_name
				tracker.set(by_sha[p['sha']], 'backport', **meta)
				p['id'] = by_sha[p['sha']]

		state.move_layer(repo, into, new_tip, 'backport %s' % ', '.join(p['origin'][:12] for p in picked), mark)
		return {'layer': into, 'picked': picked}


# branch bookkeeping

def branches(repo, remote=None, prune=False):
	"""Series and upstream branches with their state; stale ones after merge or rejection."""
	git = repo.git
	journal = repo.journal()
	all_series = series_mod.load_all(journal)
	known = {}
	for name, m in all_series.items():
		done = m.get('state') in ('merged', 'rejected')
		for b in [m.get('branch')] + [v['branch'] for v in (m.get('variants') or {}).values()]:
			if b:
				known[b] = (name, m.get('state'), done)
		prepared = (m.get('prepared') or {}).get('branch')
		if prepared:
			known[prepared] = (name, m.get('state'), done)
	rows = []
	for b in git.lines('for-each-ref', '--format=%(refname:short)', 'refs/heads/series/', 'refs/heads/upstream/'):
		name, st, done = known.get(b, (None, None, False))
		rows.append({'branch': b, 'series': name, 'state': st, 'stale': done, 'unknown': name is None,
			     'where': 'local'})
	if remote:
		git.run('fetch', '--quiet', '--prune', remote, check=False)
		by_upstream_branch = {m['upstream_branch']: n for n, m in all_series.items() if m.get('upstream_branch')}
		for short in git.lines('for-each-ref', '--format=%(refname:lstrip=3)', 'refs/remotes/%s/' % remote):
			if short == 'HEAD' or short not in by_upstream_branch:
				continue
			name = by_upstream_branch[short]
			st = all_series[name].get('state')
			rows.append({'branch': short, 'series': name, 'state': st, 'stale': st in ('merged', 'rejected'),
				     'unknown': False, 'where': remote})
	deleted = []
	if prune:
		stale = [r for r in rows if r['stale']]
		local = [r for r in stale if r['where'] == 'local' and not repo.checked_out(r['branch'])]
		if local:
			tr = RefTransaction(git)
			for r in local:
				tr.delete('refs/heads/' + r['branch'], git.rev('refs/heads/' + r['branch']))
			tr.commit()
		far = [r for r in stale if r['where'] != 'local']
		if far:
			git.run('push', '--quiet', remote, *[':refs/heads/' + r['branch'] for r in far])
		deleted = ['%s:%s' % (r['where'], r['branch']) for r in local + far]
	return {'branches': rows, 'deleted': deleted}


# upstream mirrors

def cache_dir():
	return Path(os.environ.get('XDG_CACHE_HOME') or Path.home() / '.cache') / 'gitum' / 'mirrors'


def mirror(repo, name):
	"""Keep a shared bare mirror of an upstream URL and fetch it into this repository."""
	git = repo.git
	cfg = repo.journal().config
	if name not in cfg.upstreams:
		raise GitumError('unknown upstream %s' % name)
	up = cfg.upstreams[name]
	if not up.url:
		raise GitumError('upstream %s has no url in gitum.toml' % name)
	key = re.sub(r'[^A-Za-z0-9._-]+', '_', up.url.split('://')[-1]).strip('_')
	path = cache_dir() / ('%s-%s.git' % (key[-60:], hashlib.sha1(up.url.encode()).hexdigest()[:8]))
	if not path.exists():
		path.parent.mkdir(parents=True, exist_ok=True)
		git.run('clone', '--quiet', '--mirror', up.url, str(path))
	else:
		git.at(path).run('remote', 'update', '--prune')
	remote = up.remote or name
	if git.run('remote', 'get-url', remote, check=False).returncode != 0:
		git.run('remote', 'add', remote, str(path))
	git.run('fetch', '--quiet', '--tags', remote)
	return {'upstream': name, 'mirror': str(path), 'remote': remote}
